/** Left half of the name. */
export const FIRST_WORDS: readonly string[] = [...ADJECTIVES, ...COLORS, ...STONES];
/** Right half of the name. */
export const SECOND_WORDS: readonly string[] = [...ANIMALS, ...FLOWERS, ...INSECTS];

function pick(words: readonly string[]): string {
  return words[Math.floor(Math.random() * words.length)]!;
}

/**
 * A random `<first>-<second>` name. `taken` is the fleet's current names — we
 * resample past them, and fall back to a numeric suffix if the dictionary is
 * somehow exhausted, so the button always yields something usable.
 */
export function randomAgentName(taken: ReadonlySet<string> = new Set()): string {
  for (let i = 0; i < 50; i++) {
    const name = `${pick(FIRST_WORDS)}-${pick(SECOND_WORDS)}`;
    if (!taken.has(name)) return name;
  }
  const base = `${pick(FIRST_WORDS)}-${pick(SECOND_WORDS)}`;
  for (let n = 2; n < 1000; n++) {
    const name = `${base}-${n}`;
    if (name.length <= 31 && !taken.has(name)) return name;
  }
  return base;
}
